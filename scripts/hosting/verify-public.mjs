import assert from 'node:assert/strict';
import { join } from 'node:path';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { issueGateCookie } from '../../src/lib/gate/session.server.ts';
import { resolveHostingRuntime } from './runtime-path.mjs';

const runtime = resolveHostingRuntime('DayTradeTycoon');
process.loadEnvFile(join(runtime, 'secrets/app.env'));
process.env.NODE_ENV = 'production';
const origin = process.env.BETTER_AUTH_URL;
const request = (path, options = {}) => fetch(new URL(path, origin), { ...options, signal: AbortSignal.timeout(20000) });
const health = await request('/api/health');
assert.equal(health.status, 200);
assert.equal((await health.json()).ok, true);
const home = await request('/');
assert.equal(home.status, 200);
assert.equal(home.headers.get('x-content-type-options'), 'nosniff');
const html = await home.text();
assert.match(html, /當沖大富翁/);
const assets = [...new Set([...html.matchAll(/(?:src|href)="(\/assets\/[^"?#]+)[^"]*"/g)].map(match => match[1]))];
assert.ok(assets.length > 0);
for (const path of assets) assert.equal((await request(path)).status, 200, path);
const license = await request('/license');
assert.equal(license.status, 200);
assert.match(await license.text(), /從第一筆有計畫的操作開始/);
const trial = await request('/try');
assert.equal(trial.status, 200);
assert.equal(trial.headers.getSetCookie().length, 0);
const trialHtml = await trial.text();
assert.match(trialHtml, /送出前，先看清楚這一張單/);
const trialAssets = [...new Set([...trialHtml.matchAll(/(?:src|href)="(\/assets\/[^"?#]+)[^"]*"/g)].map(match => match[1]))];
assert.ok(trialAssets.some(path => /\/try-/.test(path)), 'Public trial chunk must be linked');
for (const path of trialAssets) assert.equal((await request(path)).status, 200, path);
assert.equal((await request('/api/gate')).status, 200);
assert.equal((await request('/api/tape')).status, 403);
assert.equal((await request('/_serverFn/public-trial-probe')).status, 403);
assert.equal((await request('/api/admin/setup')).status, 403);
assert.equal((await request('/api/download/offline')).status, 403);
assert.equal((await request('/api/course-inquiries')).status, 403);
// Invalid content proves the public intake reaches validation without creating a lead.
const inquiryValidation = await request('/api/course-inquiries', {
  method: 'POST', headers: { origin, 'content-type': 'application/json' }, body: '{}',
});
assert.equal(inquiryValidation.status, 400);
assert.equal(inquiryValidation.headers.getSetCookie().length, 0);
assert.match(inquiryValidation.headers.get('cache-control'), /no-store/);
const cookie = issueGateCookie().split(';')[0];
const retiredTape = await request('/api/tape?fresh=1', { headers: { cookie } });
assert.equal(retiredTape.status, 410, 'Legacy projection data must remain retired');
const retiredPayload = await retiredTape.json();
assert.deepEqual(retiredPayload.days, []);
assert.equal(retiredPayload.refreshEnabled, false);
assert.match(retiredTape.headers.get('cache-control'), /no-store/);
const setup = await request('/api/admin/setup', { headers: { cookie } });
assert.equal(setup.status, 200);
const setupState = await setup.json();
assert.equal(typeof setupState.available, 'boolean');
assert.equal(setupState.configured, true);
const download = await request('/api/download/offline', { headers: { cookie } });
assert.equal(download.status, 200);
assert.equal(download.headers.get('content-type'), 'application/zip');
assert.match(download.headers.get('cache-control'), /no-store/);
const bytes = Buffer.from(await download.arrayBuffer());
const expected = readFileSync(new URL('../../downloads/daytrade-tycoon-offline.zip', import.meta.url));
const digest = data => createHash('sha256').update(data).digest('hex');
assert.equal(digest(bytes), digest(expected));
const manual = await request('/manual', { headers: { cookie } });
assert.equal(manual.status, 200);
// Admission is resolved in the browser, so the initial HTML has no PDF anchor.
// Check the versioned artifact here; verify the rendered download in Chrome separately.
const manualSource = JSON.parse(readFileSync(new URL('../../docs/pdf-source.json', import.meta.url), 'utf8'));
assert.match(manualSource.version, /^\d{4}-\d{2}-\d{2}(?:-[a-z0-9]+)?$/);
const pdfHref = `/daytrade-tycoon-manual.pdf?v=${encodeURIComponent(manualSource.version)}`;
const pdf = await request(pdfHref, { headers: { cookie } });
assert.equal(pdf.status, 200);
assert.match(pdf.headers.get('content-type') ?? '', /application\/pdf/);
const pdfBytes = Buffer.from(await pdf.arrayBuffer());
const expectedPdf = readFileSync(new URL('../../public/daytrade-tycoon-manual.pdf', import.meta.url));
assert.equal(digest(pdfBytes), digest(expectedPdf), 'Learner PDF download must match the current manual');
console.log(JSON.stringify({ verified: true, origin, health: 200, assets: assets.length, publicTrial: 200, trialAssets: trialAssets.length, trialIssuesCookie: false, publicInquiryValidation: 400, privateInquiryList: 403, ownerSetup: setupState.available ? 'ready-uninitialized' : 'initialized', unsignedDownload: 403, signedDownload: 200, zipBytes: bytes.length, zipSha256: digest(bytes), pdfHref, pdfBytes: pdfBytes.length, pdfSha256: digest(pdfBytes) }));
